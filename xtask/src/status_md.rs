//! `cargo xtask status-md`: `docs/status.md`'s headline, rendered from the
//! last gate run instead of pasted.
//!
//! The headline was hand-copied from commit messages for a month, and it
//! drifted: cells of four thousand characters of "N before X" history, a
//! paragraph quoting 2296/2296 under a headline of 2515, and three documents
//! giving three ptdiff figures on one day (`docs/history/audit-2026-09-22.md` §9). The gates already
//! write every number to `target/gates/status.json` (`ratchet.rs`); this
//! renders that file into the block between the two markers and leaves the
//! rest of the document alone. History stays where it belongs, in git and
//! the journal.
//!
//! Refuses a run that is red, or one whose fingerprint is not this tree's —
//! a headline must describe the code it sits beside.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};
use serde_json::Value;

const BEGIN: &str = "<!-- status:begin — generated by `cargo xtask status-md`; edits here are overwritten -->";
const END: &str = "<!-- status:end -->";

pub fn run(check: bool) -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().expect("xtask sits in the workspace");
    let status_path = crate::ratchet::gates_dir().join("status.json");
    let text = std::fs::read_to_string(&status_path)
        .with_context(|| format!("{} — run `scripts/gates.sh` first", status_path.display()))?;
    let status: Value = serde_json::from_str(&text)?;
    if status["ok"] != Value::Bool(true) {
        anyhow::bail!("the last gate run was red — a headline is rendered from a green one");
    }
    let fingerprint = crate::fresh::tree_fingerprint();
    if status["fingerprint"].as_str() != Some(fingerprint.as_str()) {
        anyhow::bail!("target/gates/status.json was written for another tree — run `scripts/gates.sh` again");
    }
    let block = render(&status);

    let doc_path = root.join("docs/status.md");
    let doc = std::fs::read_to_string(&doc_path)?;
    let (Some(b), Some(e)) = (doc.find(BEGIN), doc.find(END)) else {
        anyhow::bail!("docs/status.md has no `{BEGIN}` … `{END}` block");
    };
    let updated = format!("{}{BEGIN}\n{block}{}", &doc[..b], &doc[e..]);
    if check {
        if updated != doc {
            anyhow::bail!("docs/status.md's headline is not the last gate run's — `cargo xtask status-md`");
        }
        println!("docs/status.md's headline matches target/gates/status.json");
        return Ok(());
    }
    std::fs::write(&doc_path, updated)?;
    println!("docs/status.md: headline rendered from the gate run at {}", status["head"].as_str().unwrap_or("?"));
    Ok(())
}

/// The headline table. Every value is read from `status`; the third column
/// is fixed text saying what the gate grades and what it is blind to.
fn render(status: &Value) -> String {
    let g = |gate: &str, key: &str| status["gates"][gate]["totals"][key].as_u64();
    let set = |gate: &str, key: &str| status["gates"][gate]["sets"][key].as_u64();
    let n = |v: Option<u64>| v.map_or_else(|| "?".to_owned(), |v| v.to_string());
    let stage = |name: &str| status["stages"][name]["note"].as_str().map(str::trim).unwrap_or("").to_owned();

    let mut rows: Vec<[String; 3]> = Vec::new();
    let tests = stage("tests");
    if !tests.is_empty() {
        rows.push(["`cargo test`".into(), tests, "the workspace under `--profile quick`; `kg-ty`'s debug assertions run only here".into()]);
    }
    let corpus = stage("corpus");
    if !corpus.is_empty() {
        rows.push(["`corpus`".into(), corpus, "every reference file round-trips losslessly and parses clean".into()]);
    }
    let decidable = g("strict", "conformance-passed").zip(g("strict", "conformance-failed")).map(|(p, f)| p + f);
    rows.push([
        "`conformance`".into(),
        format!("**{}/{}** decidable, {} undecidable", n(g("strict", "conformance-passed")), n(decidable), n(g("strict", "conformance-undecidable"))),
        "accept/reject and `Error N` per assertion; must stay 100% — blind to positions and messages".into(),
    ]);
    rows.push([
        "`conformance --strict`".into(),
        format!("**{}** failing", n(g("strict", "strict-failed"))),
        "what would fail if we claimed completeness; ratcheted per assertion".into(),
    ]);
    rows.push([
        "`errors`".into(),
        format!(
            "**{}** disagree, {} agree, {} parse-agree, {} silent, of {}",
            n(set("errors", "disagree")),
            n(g("errors", "agree")),
            n(g("errors", "parse-agree")),
            n(g("errors", "ours-silent")),
            n(g("errors", "graded"))
        ),
        "our first error's position and message against `kg-oracle --errors`, every must-reject snippet".into(),
    ]);
    rows.push([
        "`ptdiff`".into(),
        format!("**{}**/{} structural, {} exact", n(set("ptdiff", "structural")), n(g("ptdiff", "graded")), n(g("ptdiff", "exact"))),
        "our ParseTree walk against the reference's recorded one, call by call; exact is blind-sided by positions (divergence #25)".into(),
    ]);
    // What neither agreed, crashed nor was declined disagreed: the ledger
    // keeps no set of its own for it.
    let backend_disagree = (|| Some(g("backend", "graded")? - g("backend", "agree")? - g("backend", "crash")? - g("backend", "declined")?))();
    rows.push([
        "`backend`".into(),
        format!(
            "**{}**/{} agree ({} of {} walked); {} disagree, {} crash, {} declined; the first backend error line the same in {}/{} rejected alike",
            n(g("backend", "agree")),
            n(g("backend", "graded")),
            n(g("backend", "walked-agree")),
            n(g("backend", "walked")),
            n(backend_disagree),
            n(g("backend", "crash")),
            n(g("backend", "declined")),
            n(set("backend", "message")),
            n(g("backend", "messages"))
        ),
        "the compat `kanagawa` through the real C++ backend, graded as `syntax-test.py` grades".into(),
    ]);
    // Graded and neither equal nor failed on the reference's side: differ.
    let output_differ = (|| Some(g("output", "graded")? - set("output", "equal")? - g("output", "theirs-failed")?))();
    rows.push([
        "`output`".into(),
        format!(
            "**{}**/{} identical modulo locations, {} byte-identical; {} differ, {} the reference failed; locations {}/{}",
            n(set("output", "equal")),
            n(g("output", "graded")),
            n(set("output", "exact")),
            n(output_differ),
            n(g("output", "theirs-failed")),
            n(g("output", "locations-agree")),
            n(g("output", "locations"))
        ),
        "every file `kanagawa --backend=sv` writes, ours against the reference's, over the programs it writes RTL for".into(),
    ]);
    rows.push([
        "`repoint`".into(),
        format!("**{}/{}**", n(g("repoint", "passed")), n(g("repoint", "graded"))),
        "upstream's own runner over whole test files".into(),
    ]);
    rows.push([
        "`cli`".into(),
        format!("**{}/{}**", n(g("cli", "passed")), n(g("cli", "graded"))),
        "upstream's own CLI tests (`test/compiler/cli`) and every mode's `--help` against the reference binary's".into(),
    ]);
    rows.push([
        "`loop-left`".into(),
        format!(
            "**{}**/{} roots leave what the reference leaves; ours only {} over {} roots, theirs only {}; rounds agree {}/{}; {} near the guard",
            n(set("loop-left", "agree")),
            n(g("loop-left", "graded")),
            n(set("loop-left", "ours-only")),
            n(g("loop-left", "ours-only-roots")),
            n(set("loop-left", "theirs-only")),
            n(set("loop-left", "rounds-agree")),
            n(g("loop-left", "graded")),
            n(set("loop-left", "near-guard"))
        ),
        "the instances the program-wide loop leaves undecided and its round count, per root the reference compiles, against `kg-oracle --loop`".into(),
    ]);
    rows.push([
        "`lint`".into(),
        ["mangled-text", "mangled-readers", "message-test", "env-verdict", "type-key-literal"]
            .iter()
            .map(|r| format!("{r} {}", n(set("lint", r))))
            .collect::<Vec<_>>()
            .join(", "),
        "retiring spellings in production code (`xtask/src/lint.rs`); each count may fall, not rise".into(),
    ]);
    rows.push([
        "`resilience`".into(),
        format!(
            "{} buffers; hover answered **{}**, copies {}, silent {}; completion {} lists, {}/{} candidates with a detail",
            n(g("resilience", "buffers")),
            n(g("resilience", "hover-answered")),
            n(g("resilience", "hover-copies")),
            n(g("resilience", "hover-silent")),
            n(g("resilience", "completion-graded")),
            n(g("resilience", "completion-candidates-typed")),
            n(g("resilience", "completion-candidates"))
        ),
        "hover and completion on broken buffers, as the editor answers them from the loop; every answer ratcheted (sprint W3.7)".into(),
    ]);
    let edits = stage("edit-identity");
    if !edits.is_empty() {
        rows.push([
            "`edit-identity`".into(),
            edits,
            "a warm database after each kind of edit and its undo, against a fresh one, every root; the warm one is the editor's, its last answer `kg check`'s (sprint W7.6)".into(),
        ]);
    }
    rows.push([
        "`shadow`".into(),
        format!(
            "{} steps after an edit; keys agreed in **{}**/{} module-rounds, restored equal {}; {} steps kept whole; {} unequal",
            n(g("shadow", "graded")),
            n(g("shadow", "agreed")),
            n(g("shadow", "rounds")),
            n(g("shadow", "equal")),
            n(set("shadow", "kept")),
            n(set("shadow", "unequal"))
        ),
        "the editor's kept loop against the next run's own, each round restored, its positions carried through the edit and keyed by its copies and by what it read across the module boundary; and every prefix pass the editor reuses, checked against the pass run (`edit-identity`; sprint W7.5d, D1 steps 1–3)".into(),
    ]);
    let bench = stage("bench");
    if !bench.is_empty() {
        rows.push(["`bench` keystroke".into(), bench, "the editor's first answer, then its last at the fixpoint; a tripwire, not a target (`CLAUDE.md`)".into()]);
    }
    let mem = stage("mem");
    if !mem.is_empty() {
        rows.push(["`mem`".into(), mem, "peak memory per use case — `kg check`, the editor opening a file and after five edits — against `memory-budgets.json`; the largest program shown".into()]);
    }

    let mut out = String::new();
    let _ = writeln!(out, "Rendered from the gate run at `{}`.\n", status["head"].as_str().unwrap_or("?"));
    let _ = writeln!(out, "| Gate | Value | What it grades |\n|---|---|---|");
    for [a, b, c] in rows {
        let _ = writeln!(out, "| {a} | {b} | {c} |");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every number comes from the file: a value missing from it renders as
    /// `?`, never as a stale figure.
    #[test]
    fn the_headline_reads_every_number_from_status_json() {
        let status = serde_json::json!({
            "head": "abc1234",
            "stages": { "tests": { "ok": true, "note": "passed 7 failed 0" } },
            "gates": {
                "strict": { "totals": { "conformance-passed": 10, "conformance-failed": 0, "conformance-undecidable": 3, "strict-failed": 2 } },
                "ptdiff": { "sets": { "structural": 5 }, "totals": { "graded": 9, "exact": 0 } },
            }
        });
        let md = render(&status);
        assert!(md.contains("`abc1234`"), "{md}");
        assert!(md.contains("| `cargo test` | passed 7 failed 0 |"), "{md}");
        assert!(md.contains("**10/10** decidable, 3 undecidable"), "{md}");
        assert!(md.contains("**2** failing"), "{md}");
        assert!(md.contains("**5**/9 structural, 0 exact"), "{md}");
        assert!(md.contains("| `repoint` | **?/?** |"), "{md}");
        // A derived count is `?` while any of its terms is.
        assert!(md.contains("; ? disagree, ? crash"), "{md}");
    }

    /// The counts no ledger keeps are derived from those it does, and the
    /// rows the run's stages carry are rendered: `backend`'s disagreements
    /// and `output`'s differences, `resilience`, `edit-identity` and the
    /// keystroke. Red with a derivation reading a key no ledger writes.
    #[test]
    fn derived_counts_and_stage_rows_render() {
        let status = serde_json::json!({
            "head": "abc1234",
            "stages": {
                "edit-identity": { "ok": true, "note": " 348 identical, 0 differ" },
                "bench": { "ok": true, "note": "worst 321.73ms on test/library/processor/risc-v.k" }
            },
            "gates": {
                "backend": { "sets": { "message": 993 }, "totals": { "agree": 3267, "graded": 3270, "crash": 1, "declined": 1, "walked": 2422, "walked-agree": 2421, "messages": 1102 } },
                "output": { "sets": { "equal": 266, "exact": 24 }, "totals": { "graded": 274, "theirs-failed": 7, "locations": 10, "locations-agree": 5 } },
                "resilience": { "totals": { "buffers": 140, "hover-answered": 1500, "hover-copies": 141, "hover-silent": 750, "completion-graded": 1400, "completion-candidates": 60000, "completion-candidates-typed": 59000 } },
            }
        });
        let md = render(&status);
        assert!(md.contains("1 disagree, 1 crash, 1 declined; the first backend error line the same in 993/1102"), "{md}");
        assert!(md.contains("1 differ, 7 the reference failed"), "{md}");
        assert!(md.contains("140 buffers; hover answered **1500**, copies 141, silent 750; completion 1400 lists, 59000/60000 candidates with a detail"), "{md}");
        assert!(md.contains("| `edit-identity` | 348 identical, 0 differ |"), "{md}");
        assert!(md.contains("worst 321.73ms on test/library/processor/risc-v.k"), "{md}");
    }
}
