//! Backend runs remembered by what the backend was told (the gates' cache;
//! `docs/plans/performance.md` §4).
//!
//! A worker's run is a function of the recording it replays, the library it
//! replays into, and this crate's replay code: the recording carries every
//! call, `InitCompiler`'s options and the command line among them, and the
//! files the backend writes are named by those options relative to the
//! working directory. So a gate that compiles 3270 programs after a change
//! that moved a handful of walks need not start 3270 backends. [`Cache`]
//! keeps, per run, the verdict, both output streams and the files written
//! under one named directory, and replays them when the same run comes
//! again.
//!
//! Only the gates turn it on (`KG_BACKEND_CACHE=<dir>`); `kg build`
//! without the variable is untouched. What keeps it honest:
//!
//! - **The key is the whole input, compared, not hashed.** An entry stores
//!   the recording and a header naming the library (path, size, modified
//!   time), the replay code, and the captured directory; a hit compares
//!   them byte for byte. The hash only names the entry's directory.
//! - **Only verdicts are kept.** A crash, a signal, a library that would
//!   not load or a recording the worker could not read is not a function of
//!   the recording; it is run again every time. The one exception is a run
//!   past the budget the gates set (`KG_BACKEND_CACHE_BUDGET_SECS`): the
//!   gates grade it a crash either way, and `test/library/processor/
//!   risc-v.k`, which the reference itself takes over 25 minutes and 8 GB
//!   to compile, cost every run of the backend gate 15 minutes to learn it
//!   again. The budget, in seconds and in megabytes, is in the key.
//! - **The premise is re-proven.** With `KG_BACKEND_CACHE_VERIFY=N` one hit
//!   in `N`, at random, runs the backend anyway and compares (`1`: every
//!   hit); a difference is written under `<dir>/mismatches/`, which the
//!   gates read and fail on, and the fresh run replaces the entry. The full
//!   gates sample, so every entry is re-run sooner or later — except a run
//!   stopped over budget, whose stopping depends on the machine's load.

use std::collections::BTreeMap;
use std::hash::{DefaultHasher, Hash, Hasher};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use crate::isolate::Verdict;

/// The cache directory; setting it turns the cache on.
pub const DIR_VAR: &str = "KG_BACKEND_CACHE";
/// A directory, relative to the working directory, whose files a run
/// writes are kept with it and restored on a hit. Unset: no files are kept
/// or restored.
pub const FILES_VAR: &str = "KG_BACKEND_CACHE_FILES";
/// `N`: run the backend on one hit in `N`, at random, and record any
/// difference; `1` runs it on every hit.
pub const VERIFY_VAR: &str = "KG_BACKEND_CACHE_VERIFY";
/// Seconds a worker may run before it is killed and its run kept as over
/// budget — below the gates' own kill (`KG_CHILD_SECS`), which would take
/// the answer with it.
pub const BUDGET_VAR: &str = "KG_BACKEND_CACHE_BUDGET_SECS";
/// Megabytes this process and its worker may hold together — the gates'
/// own group budget (`KG_CHILD_MEM_MB`), sampled more often than they do,
/// so the run is stopped here, and kept, before they stop it.
pub const BUDGET_MB_VAR: &str = "KG_BACKEND_CACHE_BUDGET_MB";
/// Where a verify run's differences go, one file per entry.
pub const MISMATCHES: &str = "mismatches";

/// The entry format, and the replay code: a change to how a recording is
/// decoded or replayed is a different backend run. The code is keyed by its
/// [`meaningful`] text — a comment or a test edited in these files keeps
/// the cache, where it once discarded all of it (~3 GB, minutes of cold
/// runs); any other edit, a trailing comment on a line of code included,
/// still moves the key, and the gates' sampled verification re-proves the
/// entries it keeps.
///
/// `backend.rs` is in it for `replay_call`, which turns each recorded call
/// back into one to the library (generated by `cargo xtask codegen`), and
/// `kg-backend-sys`'s `options.rs` for how `Options` is marshalled: an edit
/// to either is another backend run, which only the sampled re-run would
/// otherwise have noticed (sprint W6).
const FORMAT: &str = "kg-backend-cache 1";
const REPLAY_SOURCES: [&str; 6] = [
    include_str!("cache.rs"),
    include_str!("isolate.rs"),
    include_str!("real.rs"),
    include_str!("record.rs"),
    include_str!("backend.rs"),
    include_str!("../../kg-backend-sys/src/options.rs"),
];

/// A run with its streams and files: what a hit gives back.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Captured {
    pub verdict: Verdict,
    pub stdout: Vec<u8>,
    pub stderr: Vec<u8>,
    /// Files written under the captured directory, by `/`-separated path
    /// relative to it.
    pub files: BTreeMap<String, Vec<u8>>,
    /// Killed over its [`Budget`], and why: a crash, and kept.
    pub over_budget: Option<String>,
}

/// How long, and how large, a worker may grow under the gates' cache.
#[derive(Copy, Clone, Debug, Default, PartialEq, Eq)]
pub struct Budget {
    pub secs: Option<u64>,
    pub mb: Option<u64>,
}

impl Budget {
    pub fn from_env() -> Budget {
        let var = |name| std::env::var(name).ok().and_then(|v| v.parse().ok());
        Budget { secs: var(BUDGET_VAR), mb: var(BUDGET_MB_VAR) }
    }

    pub fn is_none(&self) -> bool {
        self.secs.is_none() && self.mb.is_none()
    }
}

/// What a run stopped for its time says.
pub fn over_time(secs: u64) -> String {
    format!("the backend ran over its time budget of {secs} s ({BUDGET_VAR})")
}

/// What a run stopped for its size says.
pub fn over_memory(mb: u64, limit: u64) -> String {
    format!("the backend reached {mb} MB with its frontend, over their budget of {limit} MB ({BUDGET_MB_VAR})")
}

/// The cache as one run sees it.
#[derive(Clone, Debug)]
pub struct Cache {
    pub dir: PathBuf,
    /// The captured directory: where its files are, and its name as given
    /// (the name is part of the key; the place is not).
    pub files: Option<(PathBuf, String)>,
    /// Re-run one hit in this many; 0 never.
    pub verify: u32,
    /// When a worker is killed as over budget.
    pub budget: Budget,
}

impl Cache {
    /// The cache the environment asks for, if any.
    pub fn from_env() -> Option<Cache> {
        let dir = std::env::var_os(DIR_VAR).filter(|d| !d.is_empty())?;
        let files = std::env::var(FILES_VAR).ok().filter(|f| !f.is_empty()).map(|name| {
            let cwd = std::env::current_dir().unwrap_or_default();
            (cwd.join(&name), name)
        });
        let verify = std::env::var(VERIFY_VAR).ok().and_then(|v| v.parse().ok()).unwrap_or(0);
        Some(Cache { dir: PathBuf::from(dir), files, verify, budget: Budget::from_env() })
    }

    /// Everything but the recording that decides a run.
    fn header(&self, library: &Path) -> String {
        let (size, modified) = std::fs::metadata(library).map_or((0, 0), |m| {
            let modified = m.modified().ok().and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok()).map_or(0, |d| d.as_nanos());
            (m.len(), modified)
        });
        let mut replay = DefaultHasher::new();
        for source in REPLAY_SOURCES {
            meaningful(source).hash(&mut replay);
        }
        let files = self.files.as_ref().map_or("", |(_, name)| name.as_str());
        let budget = |b: Option<u64>| b.map_or_else(String::new, |b| b.to_string());
        let (secs, mb) = (budget(self.budget.secs), budget(self.budget.mb));
        format!(
            "{FORMAT}\nreplay {:016x}\nlibrary {}\nsize {size}\nmodified {modified}\nfiles {files}\nbudget {secs} s {mb} MB\n",
            replay.finish(),
            library.display()
        )
    }

    fn entry(&self, header: &str, recording: &[u8]) -> PathBuf {
        let mut name = String::new();
        for seed in [0u8, 1] {
            let mut h = DefaultHasher::new();
            seed.hash(&mut h);
            header.hash(&mut h);
            recording.hash(&mut h);
            name.push_str(&format!("{:016x}", h.finish()));
        }
        self.dir.join(&name[..2]).join(name)
    }

    /// The stored run for this input, if one is stored.
    pub fn load(&self, library: &Path, recording: &[u8]) -> Option<Captured> {
        let header = self.header(library);
        let entry = self.entry(&header, recording);
        if std::fs::read(entry.join("header")).ok()? != header.as_bytes() || std::fs::read(entry.join("recording")).ok()? != recording {
            return None;
        }
        let (verdict, over_budget) = match std::fs::read_to_string(entry.join("verdict")).ok()?.as_str() {
            "compiled" => (Verdict::Compiled, None),
            "rejected" => (Verdict::Rejected, None),
            "init-failed" => (Verdict::InitFailed, None),
            over => {
                let how = over.strip_prefix("over-budget ")?.to_owned();
                (Verdict::Crashed { how: how.clone() }, Some(how))
            }
        };
        let mut files = BTreeMap::new();
        read_tree(&entry.join("files"), "", &mut files).ok()?;
        // Last used now: the gates evict the least recently used first.
        let _ = std::fs::File::options().write(true).open(entry.join("header")).and_then(|f| f.set_modified(std::time::SystemTime::now()));
        Some(Captured {
            verdict,
            stdout: std::fs::read(entry.join("stdout")).ok()?,
            stderr: std::fs::read(entry.join("stderr")).ok()?,
            files,
            over_budget,
        })
    }

    /// Keep `run`, if it is a verdict. A failure to write is a miss next
    /// time, never an error: the cache is only ever an optimisation.
    pub fn store(&self, library: &Path, recording: &[u8], run: &Captured) {
        let verdict = match (&run.verdict, &run.over_budget) {
            (Verdict::Compiled, _) => "compiled".to_owned(),
            (Verdict::Rejected, _) => "rejected".to_owned(),
            (Verdict::InitFailed, _) => "init-failed".to_owned(),
            (Verdict::Crashed { .. }, Some(how)) => format!("over-budget {how}"),
            (Verdict::LoadFailed, _) | (Verdict::Crashed { .. }, None) => return,
        };
        let header = self.header(library);
        let entry = self.entry(&header, recording);
        let Some(parent) = entry.parent() else { return };
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let tmp = parent.join(format!(".tmp-{}-{}", std::process::id(), NEXT.fetch_add(1, Ordering::Relaxed)));
        let written = (|| -> std::io::Result<()> {
            std::fs::create_dir_all(tmp.join("files"))?;
            for (name, bytes) in &run.files {
                let path = tmp.join("files").join(name);
                if let Some(dir) = path.parent() {
                    std::fs::create_dir_all(dir)?;
                }
                std::fs::write(path, bytes)?;
            }
            std::fs::write(tmp.join("stdout"), &run.stdout)?;
            std::fs::write(tmp.join("stderr"), &run.stderr)?;
            std::fs::write(tmp.join("verdict"), verdict)?;
            std::fs::write(tmp.join("recording"), recording)?;
            std::fs::write(tmp.join("header"), &header)?;
            let _ = std::fs::remove_dir_all(&entry);
            std::fs::rename(&tmp, &entry)
        })();
        if written.is_err() {
            let _ = std::fs::remove_dir_all(&tmp);
        }
    }

    /// Whether this hit is one to run again.
    pub fn verifies(&self) -> bool {
        match self.verify {
            0 => false,
            1 => true,
            n => {
                let mut h = DefaultHasher::new();
                (std::time::SystemTime::now(), std::process::id()).hash(&mut h);
                h.finish().is_multiple_of(u64::from(n))
            }
        }
    }

    /// Write a hit's files where the run would have written them.
    pub fn restore(&self, run: &Captured) -> std::io::Result<()> {
        let Some((root, _)) = &self.files else { return Ok(()) };
        for (name, bytes) in &run.files {
            let path = root.join(name);
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)?;
            }
            std::fs::write(path, bytes)?;
        }
        Ok(())
    }

    /// Record that a fresh run of a stored input came out otherwise.
    pub fn mismatch(&self, library: &Path, recording: &[u8], stored: &Captured, fresh: &Captured) {
        let entry = self.entry(&self.header(library), recording);
        let name = entry.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        let dir = self.dir.join(MISMATCHES);
        let _ = std::fs::create_dir_all(&dir);
        let _ = std::fs::write(dir.join(name), difference(stored, fresh));
    }
}

/// A source file as it bears on what the worker does: comment-only lines
/// (`//`, `///`, `//!`) dropped, runs of whitespace collapsed, and the test
/// module at its end — a top-level `#[cfg(…test…)]` followed by `mod` —
/// cut off. Nothing on a line of code is ever dropped.
pub fn meaningful(source: &str) -> String {
    let lines: Vec<&str> = source.lines().collect();
    let mut out = String::with_capacity(source.len());
    for (i, line) in lines.iter().enumerate() {
        let next = lines.get(i + 1).map_or("", |l| l.trim_start());
        if line.starts_with("#[cfg(") && line.contains("test") && next.starts_with("mod ") {
            break;
        }
        let code = line.trim();
        if code.is_empty() || code.starts_with("//") {
            continue;
        }
        for word in code.split_whitespace() {
            out.push_str(word);
            out.push(' ');
        }
        out.push('\n');
    }
    out
}

/// What differs between two runs, for a person — one line each. A file
/// that differs only in its source locations (`crate::locations`) says so
/// on its line: the backend's own output varies there run to run
/// ([`location_only`]).
pub fn difference(stored: &Captured, fresh: &Captured) -> String {
    let mut out = String::new();
    if stored.verdict != fresh.verdict {
        out.push_str(&format!("verdict: stored {:?}, fresh {:?}\n", stored.verdict, fresh.verdict));
    }
    if stored.stdout != fresh.stdout {
        out.push_str("stdout differs\n");
    }
    if stored.stderr != fresh.stderr {
        out.push_str("stderr differs\n");
    }
    for name in stored.files.keys().chain(fresh.files.keys()) {
        let (a, b) = (stored.files.get(name), fresh.files.get(name));
        if a == b || out.contains(&format!("file {name}")) {
            continue;
        }
        let only = matches!((a, b), (Some(a), Some(b)) if crate::locations::modulo_locations(name, a, b).is_ok());
        out.push_str(&format!("file {name}{}\n", if only { LOCATIONS_ONLY } else { "" }));
    }
    out
}

const LOCATIONS_ONLY: &str = " (locations only)";

/// Whether a recorded [`difference`] is only files differing in their
/// source locations — the backend's own nondeterminism, not a failed
/// premise: the verdict, the streams and every file modulo locations
/// agree, which is all `output` and `backend` grade besides `exact`.
pub fn location_only(difference: &str) -> bool {
    let mut lines = difference.lines().filter(|l| !l.trim().is_empty()).peekable();
    lines.peek().is_some() && lines.all(|l| l.starts_with("file ") && l.ends_with(LOCATIONS_ONLY))
}

/// Every regular file under `root`, with its length and modified time: a
/// run's files are the ones that are new or changed afterwards.
pub fn listing(root: &Path) -> BTreeMap<String, (u64, Option<std::time::SystemTime>)> {
    let mut out = BTreeMap::new();
    let mut stack = vec![(root.to_path_buf(), String::new())];
    while let Some((dir, prefix)) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else { continue };
        for entry in entries.flatten() {
            let name = format!("{prefix}{}", entry.file_name().to_string_lossy());
            match entry.metadata() {
                Ok(m) if m.is_dir() => stack.push((entry.path(), format!("{name}/"))),
                Ok(m) if m.is_file() => {
                    out.insert(name, (m.len(), m.modified().ok()));
                }
                _ => {}
            }
        }
    }
    out
}

/// The files under `root` that are not as `before` listed them.
pub fn written(root: &Path, before: &BTreeMap<String, (u64, Option<std::time::SystemTime>)>) -> BTreeMap<String, Vec<u8>> {
    listing(root)
        .into_iter()
        .filter(|(name, stat)| before.get(name) != Some(stat))
        .filter_map(|(name, _)| std::fs::read(root.join(&name)).ok().map(|bytes| (name, bytes)))
        .collect()
}

fn read_tree(dir: &Path, prefix: &str, out: &mut BTreeMap<String, Vec<u8>>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let name = format!("{prefix}{}", entry.file_name().to_string_lossy());
        if entry.file_type()?.is_dir() {
            read_tree(&entry.path(), &format!("{name}/"), out)?;
        } else {
            out.insert(name, std::fs::read(entry.path())?);
        }
    }
    Ok(())
}

/// Hand a run's streams to this process's own.
pub fn forward(run: &Captured) {
    let mut stdout = std::io::stdout().lock();
    let _ = stdout.write_all(&run.stdout);
    let _ = stdout.flush();
    let mut stderr = std::io::stderr().lock();
    let _ = stderr.write_all(&run.stderr);
    let _ = stderr.flush();
}

#[cfg(test)]
mod tests {
    use super::{difference, location_only, meaningful, Captured};
    use crate::isolate::Verdict;

    fn run(verdict: Verdict, sv: &str) -> Captured {
        Captured {
            verdict,
            stdout: Vec::new(),
            stderr: Vec::new(),
            files: [("out/o.sv".to_owned(), sv.as_bytes().to_vec())].into(),
            over_budget: None,
        }
    }

    /// A fresh run that differs from the stored one only in which source
    /// line a location comment cites — the backend's own nondeterminism,
    /// seen on `test/logic/optimization_test_cases.k` — is a location-only
    /// difference; one in code, or in the verdict, is not. Red with every
    /// file difference called location-only, or with none.
    #[test]
    fn a_difference_in_locations_only_is_named_so() {
        let stored = run(Verdict::Compiled, "  x <= y;\t// t.k:108:9\n");
        let moved = run(Verdict::Compiled, "  x <= y;\t// t.k:126:9\n");
        let code = run(Verdict::Compiled, "  x <= z;\t// t.k:108:9\n");
        assert!(location_only(&difference(&stored, &moved)), "{}", difference(&stored, &moved));
        assert!(!location_only(&difference(&stored, &code)));
        assert!(!location_only(&difference(&stored, &run(Verdict::Rejected, "  x <= y;\t// t.k:126:9\n"))));
        assert!(!location_only(""));
    }

    /// A comment, a doc comment, re-indentation or an edit to the test
    /// module keeps the key; a change to code — a trailing comment on a line
    /// of code included — moves it. Red with comment lines kept, or with the
    /// test module counted.
    /// The key covers what a replay runs: the code that turns each
    /// recorded call back into one to the library, and the marshalling of
    /// `Options`, not only this crate's driver. Red with either left out.
    #[test]
    fn the_key_covers_the_replayed_calls_and_the_options() {
        // Spelled in pieces: this file is a source too, and a whole needle
        // here would find itself.
        let covered = |needle: &[&str]| super::REPLAY_SOURCES.iter().any(|s| s.contains(&needle.concat()));
        assert!(covered(&["pub(crate) fn replay", "_call<"]), "replay_call");
        assert!(covered(&["pub struct Marshalled", "Options {"]), "options.rs");
    }

    #[test]
    fn only_code_moves_the_key() {
        let base = "/// Replays.\nfn run() {\n    call(1);\n}\n\n#[cfg(test)]\nmod tests {\n    fn t() {}\n}\n";
        let commented = "//! A module.\n/// Replays, now documented.\nfn run() {\n        // why\n    call(1);\n}\n\n#[cfg(test)]\nmod tests {\n    fn t() { assert!(true); }\n}\n";
        assert_eq!(meaningful(base), meaningful(commented));
        for edit in ["fn run() {\n    call(2);\n}\n", "fn run() {\n    call(1); // traced\n}\n", "fn run() {\n    call(1);\n}\nfn more() {}\n"] {
            assert_ne!(meaningful(base), meaningful(edit), "{edit}");
        }
    }
}
