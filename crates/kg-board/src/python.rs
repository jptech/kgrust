//! The Python module for a design (`docs/plans/board-tooling.md` §7): one
//! class for the exported class, one method per function, over
//! `platform/python/kgbridge.py`, which every build copies beside it. The
//! interface is embedded whole, so the module needs nothing else; the
//! bridge's hash is embedded too, so a host talking to another build is told
//! so before it calls anything.

use std::fmt::Write as _;

use camino::{Utf8Path, Utf8PathBuf};

use crate::interface::{Function, Interface, Value};
use crate::wrapper::bridge::Plan;
use crate::{Failure, Result};

/// The module's file name, `accel.py` for `Accel`, `spram_test.py` for
/// `SpramTest`.
pub fn file_name(module: &str) -> String {
    format!("{}.py", snake(module))
}

/// Writes the module and `kgbridge.py` into `<out>/py`; returns the module.
pub fn write(interface: &Interface, plan: Option<&Plan>, clock_mhz: Option<i64>, platform: &Utf8Path, out: &Utf8Path) -> Result<Utf8PathBuf> {
    let dir = out.join("py");
    std::fs::create_dir_all(&dir).map_err(|e| Failure::Failed(format!("{dir}: {e}")))?;
    let runtime = platform.join("python/kgbridge.py");
    std::fs::copy(&runtime, dir.join("kgbridge.py")).map_err(|e| Failure::Failed(format!("{runtime}: {e}")))?;
    let path = dir.join(file_name(&interface.module));
    crate::write(&path, &module(interface, plan, clock_mhz))?;
    Ok(path)
}

pub fn module(interface: &Interface, plan: Option<&Plan>, clock_mhz: Option<i64>) -> String {
    let name = &interface.module;
    let mut py = String::new();
    let _ = writeln!(py, "\"\"\"{name}, from Python: generated by `kg board` from target/board/interface.json.");
    let _ = writeln!(py, "Do not edit; every build writes it again.\n");
    if let Some(doc) = &interface.doc {
        let _ = writeln!(py, "{}\n", doc.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\""));
    }
    let _ = writeln!(py, "Usage (kgbridge.py, beside this file, has the transports):\n");
    let _ = writeln!(py, "    from {} import {name}", snake(name));
    let _ = writeln!(py, "    api = {name}()                  # under `kg board serve`, or {name}(port=\"/dev/ttyUSB0\")");
    if let Some(f) = interface.methods.iter().find(|f| plan.is_some_and(|p| p.functions.contains(&f.name))) {
        let args: Vec<&str> = f.args.iter().map(|_| "0").collect();
        let _ = writeln!(py, "    api.{}({})", ident(&f.name), args.join(", "));
    }
    let _ = writeln!(py, "\"\"\"\n\nimport json\n\nimport kgbridge\n");
    // JSON escapes every quote inside a string, so its text never holds
    // three in a row, and it ends in `}`: a raw triple-quoted string holds it.
    let _ = writeln!(py, "# The interface description, as target/board/interface.json has it.");
    let _ = writeln!(py, "INTERFACE = json.loads(r\"\"\"\n{}\"\"\")\n", interface.to_json());
    let bridged: Vec<String> = plan.map(|p| p.functions.iter().map(|f| format!("{f:?}")).collect()).unwrap_or_default();
    let _ = writeln!(py, "# What the board's bridge serves; the rest is wired to its resources.");
    let _ = writeln!(py, "BRIDGED = frozenset({{{}}})", bridged.join(", "));
    let _ = writeln!(py, "HASH = 0x{:08x}", plan.map_or(0, |p| p.hash));
    let _ = writeln!(py, "BAUD = {}", plan.map_or(115_200, |p| p.baud));
    let _ = writeln!(py, "CLOCK_MHZ = {}\n\n", clock_mhz.map_or("None".to_owned(), |m| m.to_string()));

    let _ = writeln!(py, "class {name}(kgbridge.Device):");
    let _ = writeln!(py, "    {}\n", docstring(interface.doc.as_deref().unwrap_or(&format!("The exported class {name}."))));
    let _ = writeln!(py, "    INTERFACE = INTERFACE\n    BRIDGED = BRIDGED\n    HASH = HASH\n    BAUD = BAUD\n    CLOCK_MHZ = CLOCK_MHZ");
    for f in &interface.methods {
        let params: Vec<String> = f.args.iter().map(|a| ident(&a.name)).collect();
        let mut sig = vec!["self".to_owned()];
        sig.extend(params.iter().cloned());
        let _ = writeln!(py, "\n    def {}({}):", ident(&f.name), sig.join(", "));
        let _ = writeln!(py, "        {}", docstring(&describe(f, plan)));
        let mut call = vec![format!("{:?}", f.name)];
        call.extend(params);
        let _ = writeln!(py, "        return self._call({})", call.join(", "));
    }
    for f in &interface.callbacks {
        let bare = f.name.trim_start_matches('_');
        let _ = writeln!(py, "\n    def on_{}(self, handler):", ident(bare));
        let _ = writeln!(py, "        {}", docstring(&describe(f, plan)));
        let _ = writeln!(py, "        return self.on({:?}, handler)", f.name);
    }
    py
}

/// A function's docstring: its documentation, then its signature, protocol
/// and reach.
fn describe(f: &Function, plan: Option<&Plan>) -> String {
    let mut text = f.doc.clone().unwrap_or_default();
    if !text.is_empty() {
        text.push_str("\n\n");
    }
    let args: Vec<String> = f.args.iter().map(|a| format!("{} {}", a.ty, a.name)).collect();
    let result = f.result.as_ref().map_or("void".to_owned(), |r| r.ty.clone());
    let protocol = match f.latency {
        Some(n) => format!("latency {n}"),
        None => f.protocol.as_str().replace('_', " "),
    };
    if f.callback {
        let _ = write!(text, "Answers the callback `{}({})` -> {result} ({protocol}) with handler({}).", f.name, args.join(", "), names(&f.args));
    } else {
        let _ = write!(text, "`{}({})` -> {result} ({protocol}).", f.name, args.join(", "));
    }
    if plan.is_some_and(|p| !p.functions.contains(&f.name)) {
        text.push_str("\nWired to a board resource: callable under cocotb, not over the serial bridge.");
    }
    text
}

fn names(values: &[Value]) -> String {
    values.iter().map(|v| v.name.clone()).collect::<Vec<_>>().join(", ")
}

fn docstring(text: &str) -> String {
    let text = text.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() <= 1 {
        return format!("\"\"\"{}\"\"\"", text.trim());
    }
    let mut out = format!("\"\"\"{}\n", lines[0]);
    for line in &lines[1..] {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "        {line}");
        }
    }
    out.push_str("        \"\"\"");
    out
}

/// `SpramTest` as `spram_test`.
fn snake(name: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = name.chars().collect();
    for (i, c) in chars.iter().enumerate() {
        if c.is_uppercase() {
            let after_lower = i > 0 && (chars[i - 1].is_lowercase() || chars[i - 1].is_ascii_digit());
            let before_lower = i > 0 && chars.get(i + 1).is_some_and(|n| n.is_lowercase()) && chars[i - 1].is_uppercase();
            if after_lower || before_lower {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(*c);
        }
    }
    out
}

/// A name Python accepts: a keyword gets a trailing underscore.
fn ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del", "elif",
        "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal", "not", "or",
        "pass", "raise", "return", "try", "while", "with", "yield", "self",
    ];
    if KEYWORDS.contains(&name) { format!("{name}_") } else { name.to_owned() }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_pythons() {
        assert_eq!(snake("SpramTest"), "spram_test");
        assert_eq!(snake("Accel"), "accel");
        assert_eq!(snake("UARTBridge"), "uart_bridge");
        assert_eq!(snake("Vga2D"), "vga2_d");
        assert_eq!(ident("pass"), "pass_");
        assert_eq!(ident("add"), "add");
    }
}
